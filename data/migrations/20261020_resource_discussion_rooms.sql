-- 仅显式执行：新增独立资源讨论消息与个人阅读状态；不修改原项目消息、主题或私聊。
BEGIN;
CREATE TABLE IF NOT EXISTS chat_discussion_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id uuid NOT NULL,
    sender_id uuid NOT NULL REFERENCES app_user(id),
    sender_name varchar(255) NOT NULL,
    client_message_id uuid NOT NULL,
    content text NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 10000),
    reply_to_id bigint REFERENCES chat_discussion_message(id),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recalled_at timestamptz,
    CONSTRAINT uq_discussion_client_message UNIQUE (room_id, sender_id, client_message_id)
);
CREATE INDEX IF NOT EXISTS ix_discussion_room_message ON chat_discussion_message(room_id, id);
CREATE TABLE IF NOT EXISTS chat_discussion_member (
    room_id uuid NOT NULL,
    user_id uuid NOT NULL REFERENCES app_user(id),
    last_read_id bigint NOT NULL DEFAULT 0,
    pinned boolean NOT NULL DEFAULT false,
    starred boolean NOT NULL DEFAULT false,
    PRIMARY KEY (room_id, user_id)
);
COMMIT;
