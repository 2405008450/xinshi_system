import api from './index'
export const meetingContext=()=>api.get('/meetings/context')
export const meetingAvailability=(params,signal)=>api.get('/meetings/availability',{params,signal,timeout:60000})
export const meetingSummary=()=>api.get('/meetings/summary')
export const meetingList=(params,signal)=>api.get('/meetings',{params,signal})
export const meetingDetail=id=>api.get(`/meetings/${id}`)
export const createMeeting=data=>api.post('/meetings',data,{timeout:60000})
export const respondMeeting=(id,data)=>api.put(`/meetings/${id}/receipt`,data)
export const readMeetingReceipts=(id,versions)=>api.post(`/meetings/${id}/receipts-read`,{versions})
export const meetingClients=(keyword,signal)=>api.get('/meetings/client-options',{params:{keyword},signal})
export const meetingProjects=(project_type,keyword,signal)=>api.get('/meetings/project-options',{params:{project_type,keyword},signal})
export const confirmMeetingActual=(id,data)=>api.post(`/meetings/${id}/confirm-actual`,data,{timeout:60000})
export const saveMeetingRecord=(id,data)=>api.put(`/meetings/${id}/record`,data,{timeout:60000})
export const getMeetingTasks=(params,signal)=>api.get('/meetings/my-tasks',{params,signal})
export const updateMeetingTask=(id,data)=>api.put(`/meetings/tasks/${id}/status`,data)
