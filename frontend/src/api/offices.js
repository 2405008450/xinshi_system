import api from './index'
export const getOffices=(config={})=>api.get('/office-management',config)
export const getOfficeCities=(config={})=>api.get('/office-management/cities',config)
export const createOffice=data=>api.post('/office-management',data)
export const updateOffice=(id,data)=>api.put(`/office-management/${id}`,data)
export const getRemoteWorkers = (config = {}) => api.get('/office-management/remote-workers', config)
export const getRemoteWorkerPeople = (config = {}) => api.get('/office-management/remote-workers/people', config)
export const createRemoteWorker = data => api.post('/office-management/remote-workers', data)
export const updateRemoteWorker = (id, data) => api.put(`/office-management/remote-workers/${id}`, data)
export const deleteRemoteWorker = (id, revision) => api.delete(`/office-management/remote-workers/${id}`, { params: { revision } })
